export function getBookBySlug(slug: string): BookData | undefined {
  return books.find((b) => b.slug === slug);
}

export function getBooksByGenre(genreSlug: string): BookData[] {
  return books.filter((b) => b.genreSlug === genreSlug);
}

export function getBooksBySerie(serieSlug: string): BookData[] {
  return books
    .filter((b) => b.serieSlug === serieSlug)
    .sort((a, b) => (a.serieOrder ?? 0) - (b.serieOrder ?? 0));
}

export function getFeaturedBook(): BookData {
  const envSlug = process.env.NEXT_PUBLIC_FEATURED_BOOK_SLUG;
  if (envSlug) return books.find((b) => b.slug === envSlug) ?? books[0];
  return books.find((b) => b.featured) ?? books[0];
}
